def build_storyboard() -> str:
    lines = ["# 第15话前八图｜Gen2.6电影化表演测试", "", "## 场景色彩基准", "", "彩色二维赛璐璐动画，清晰墨线、少量网点与纸面颗粒并存；林地使用青蓝天空、青绿树冠、蓝青远山与暖灰石路，晶石保持青蓝棱面、冷白星屑与蓝灰底座，抽象画面使用当前面板可见的渐变、速度线、冲击底或留白。", ""]
    current = None
    for s in SHOTS:
        if s["clip"] != current:
            current = s["clip"]
            lines += [f"## 【片段{current}】", ""]
        lines.append(f"**分镜{s['number']}（{s['seconds']}秒）：**")
        if s["role"] == "source_locked":
            lines.append(f"分镜参考 `[{s['image']}]`")
        lines.append(f"场景环境：{s['environment']}")
        lines.append(f"环境音：{s['ambience']}")
        lines.append(f"镜头设计：{s['camera']}")
        lines.append(f"可见动作：{s['action']}")
        lines.append("台词与语气：")
        if s["dialogue"]:
            for d in s["dialogue"]:
                lines.append(f"{d['speaker']}说：“{d['script']}”（{d['voice']}）")
        else:
            lines.append("画面以动作、环境与节奏停顿承载信息。")
        lines.append(f"光影布光：{s['lighting']}")
        lines.append(s["sound"])
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def build_ledger() -> dict:
    names = sorted(BACKGROUNDS)
    panels = []
    for name in names:
        related = [s for s in SHOTS if s["image"] == name]
        bubbles = []
        for s in related:
            for d in s["dialogue"]:
                bubbles.append({
                    "id": f"{name[:-4]}_b{len(bubbles)+1:02d}", "speaker": d["speaker"],
                    "speaker_evidence": "气泡尾向、人物口型与当前面板人物位置共同确认",
                    "kind": "dialogue", "source_text": d["source"], "status": "mapped",
                    "script_text": d["script"], "target": f"片段{s['clip']}/分镜{s['number']}", "seconds": d["seconds"],
                })
        targets = {b["target"] for b in bubbles}
        speakers = {b["speaker"] for b in bubbles}
        risky = any(sum(c.isalnum() for c in b["script_text"]) >= 28 or len(re.findall(r"[。！？!?]+", b["script_text"])) >= 3 for b in bubbles)
        panel = {
            "image": name, "viewed_at_drafting": True, "source_bubble_count": len(bubbles), "bubble_audit": "pass",
            "background": {"type": BACKGROUNDS[name][0], "description": BACKGROUNDS[name][1], "evidence": "current_panel"},
            "locks": {"composition": related[0]["action"].split("；")[0] if related else "当前面板以对白承载表演关系", "visible_subjects": ["仅保留当前面板中可见人物、物件与图形元素"], "relations": ["人物与物件的接触、朝向和前后关系按当前面板锁定"], "forbidden_inferences": ["人物、道具、地点与动作结果的事实范围由当前面板可见内容界定"]},
            "coverage": "mixed" if len(targets) > 1 else "shared" if len(bubbles) >= 3 or len(speakers) >= 2 or risky else "none", "bubbles": bubbles,
        }
        if any(28 <= sum(c.isalnum() for c in b["script_text"]) < 42 for b in bubbles):
            panel["coverage_reason"] = "保留当前面板的表演连续性，并用具体视线、呼吸和手部动作承载信息。"
        if any(sum(c.isalnum() for c in b["script_text"]) >= 42 or len(re.findall(r"[。！？!?]+", b["script_text"])) >= 3 for b in bubbles):
            panel["long_take_reason"] = "当前面板的语义与听者反应在同一关系构图内沿台词逐层发展。"
        if len(speakers) >= 2 and len(bubbles) >= 3 and len(targets) < 2:
            panel["shared_reason"] = "当前面板把多说话人反应组织在同一关系构图内。"
        panels.append(panel)

    shots, performance = [], []
    for s in SHOTS:
        target = f"片段{s['clip']}/分镜{s['number']}"
        shots.append({"target": target, "role": s["role"], "source_images": [] if s["role"] == "uncited_coverage" else [s["image"]], "viewed_while_writing": s["role"] != "uncited_coverage", "evidence": "当前原格" if s["role"] == "source_locked" else "前后格的人物站位与道具状态", "purpose": "忠实呈现当前面板可见关系并执行电影化表演", "background_excerpt": f"场景环境：{s['environment']}", "source_audit": "pass", "unsupported_additions": []})
        chars = sum(sum(c.isalnum() for c in d["script"]) for d in s["dialogue"])
        if chars > 20:
            details = s["details"] or ["视线", "呼吸"]
            entry = {"target": target, "evidence": "当前面板的表情、手势、道具接触与对白顺序", "details": details, "intervals": [{"speech_seconds": sum(d["seconds"] for d in s["dialogue"]), "acting_seconds": min(s["seconds"], max(1.0, sum(d["seconds"] for d in s["dialogue"]) - 0.2))}]}
            if chars >= 42:
                entry["long_take_reason"] = "当前面板已把语义与错拍反应沿同一构图展开。"
            performance.append(entry)
    return {"version": 2, "panels": panels, "shots": shots, "performance": performance}


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "storyboard.md").write_text(build_storyboard(), encoding="utf-8")
    (OUT / "source-ledger.json").write_text(json.dumps(build_ledger(), ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(f"wrote {OUT / 'storyboard.md'}")
    print(f"wrote {OUT / 'source-ledger.json'}")
    print(f"shots={len(SHOTS)} panels={len(BACKGROUNDS)}")


if __name__ == "__main__":
    main()
